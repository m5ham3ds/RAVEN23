/// A concrete stream option shown by the app-wide quality picker.
///
/// Each entry keeps the exact owning provider and original link metadata.
/// The source catalogue retains same-height alternatives; user-facing menus
/// use bestPerQuality() to show one stable server for each resolution.
class QualityCatalogEntry {
  const QualityCatalogEntry({
    required this.providerCode,
    required this.sourceProviderCode,
    required this.sourceKey,
    required this.link,
    required this.height,
    required this.qualityLabel,
    this.adaptiveTargetHeight,
    this.isAdaptive = false,
    this.estimatedSizeBytes,
  });

  final String providerCode;

  /// The bucket whose raw link list is used to activate this exact source.
  /// This can be the owning provider or the Unified Sources aggregate bucket.
  final String sourceProviderCode;

  /// Exact key generated by [VideoUtils.videoSourceKeys] for this raw link.
  /// It differentiates same-URL, same-quality mirrors without guessing from
  /// the URL or the provider name at selection time.
  final String sourceKey;
  final RegularVideoLinks link;
  final int? height;
  final String qualityLabel;

  /// A number represents a concrete user-selectable variant of this adaptive
  /// master URL. Provider-owned Auto rows are never exposed in the catalogue.
  final int? adaptiveTargetHeight;
  final bool isAdaptive;
  final int? estimatedSizeBytes;

  /// Includes the exact signed token so a refreshed/mutated link cannot reuse
  /// an estimate calculated for a different media object or quality.
  String get sizeEstimateKey {
    final token = link.sizeToken?.trim() ?? '';
    return '$sourceProviderCode:::$sourceKey:::$qualityLabel:::$token';
  }

  QualityCatalogEntry withEstimatedSize(int? bytes) => QualityCatalogEntry(
    providerCode: providerCode,
    sourceProviderCode: sourceProviderCode,
    sourceKey: sourceKey,
    link: link,
    height: height,
    qualityLabel: qualityLabel,
    adaptiveTargetHeight: adaptiveTargetHeight,
    isAdaptive: isAdaptive,
    estimatedSizeBytes: bytes,
  );

  /// The stream host label shown below the quality. When a source has no host
  /// label, fall back to its stable provider identity rather than hiding where
  /// the selected URL came from.
  String get sourceDisplayName {
    final server = link.server?.trim();
    if (server != null && server.isNotEmpty) return server;
    final code = providerCode.trim();
    if (code.isEmpty) return 'Source';
    if (code.startsWith('unified:source:')) {
      return code.substring('unified:source:'.length);
    }
    return code;
  }

  String get formatLabel =>
      switch (VideoUtils.downloadFormat(url: link.url ?? '', link: link)) {
        'hls' => 'HLS',
        'dash' => 'DASH',
        'mp4' => 'MP4',
        'webm' => 'WebM',
        _ => 'Progressive',
      };

  String get technicalSubtitle => <String>[
    formatLabel,
    if (link.headers?.isNotEmpty == true) 'Request headers',
  ].join('  •  ');

  /// Same secondary line used by the player and the download chooser.
  String get selectionSubtitle => <String>[
    sourceDisplayName,
    technicalSubtitle,
  ].where((value) => value.trim().isNotEmpty).join(' · ');
}

/// Builds a quality catalogue from all provider results without changing the
/// active player's data source. This is deliberately separate from the
/// BetterPlayer `resolutions` map, which belongs only to the currently active
/// URL/provider and cannot be safely mutated during background discovery.
abstract final class PlaybackQualityCatalog {
  /// Discover adaptive manifest variants before building a picker used
  /// outside the already-running player (notably the download quality sheet).
  /// Requests are bounded to three concurrent manifests and retain the exact
  /// link headers/source metadata. If a manifest cannot be inspected, no fake
  /// Auto row is emitted; only concrete known qualities remain selectable.
  static Future<List<QualityCatalogEntry>> collectWithAdaptiveDiscovery({
    required Map<String, List<RegularVideoLinks>> linksByProvider,
    DateTime? now,
    String? activeProviderCode,
    String? activeSourceKey,
    String? activeStreamUrl,
    List<String>? preferredServerOrder,
  }) async {
    final candidates = <RegularVideoLinks>[];
    final seenCandidates = <String>{};
    for (final links in linksByProvider.values) {
      for (final link in links) {
        if (!AdaptiveQualityScanner.isCandidate(link)) continue;
        final url = link.url?.trim() ?? '';
        if (url.isEmpty) continue;
        final headers =
            (link.headers ?? const <String, String>{}).entries
                .map((entry) => '${entry.key.toLowerCase()}:${entry.value}')
                .toList()
              ..sort();
        final signature = '$url|${headers.join('|')}';
        if (seenCandidates.add(signature)) candidates.add(link);
      }
    }

    final scanner = AdaptiveQualityScanner();
    try {
      for (var offset = 0; offset < candidates.length; offset += 3) {
        final end = (offset + 3).clamp(0, candidates.length).toInt();
        await Future.wait(
          candidates.sublist(offset, end).map((link) async {
            final heights = await scanner.scan(link);
            if (heights.isNotEmpty) {
              link.availableHeights = heights;
              link.isAdaptive = true;
            }
          }),
        );
      }
    } finally {
      scanner.dispose();
    }

    return collect(
      linksByProvider: linksByProvider,
      now: now,
      activeProviderCode: activeProviderCode,
      activeSourceKey: activeSourceKey,
      activeStreamUrl: activeStreamUrl,
      preferredServerOrder: preferredServerOrder,
    );
  }

  static List<QualityCatalogEntry> collect({
    required Map<String, List<RegularVideoLinks>> linksByProvider,
    DateTime? now,
    String? activeProviderCode,
    String? activeSourceKey,
    String? activeStreamUrl,
    List<String>? preferredServerOrder,
  }) {
    final checkedAt = now ?? DateTime.now();
    final hostOrder =
        preferredServerOrder ?? StreamHostPriorityManager.instance.currentOrder;
    final result = <QualityCatalogEntry>[];
    final seen = <String>{};
    final sourceKeysByProvider = <String, List<String>>{
      for (final entry in linksByProvider.entries)
        entry.key: VideoUtils.videoSourceKeys(entry.value),
    };

    for (final providerEntry in linksByProvider.entries) {
      // Do not discard the aggregate bucket wholesale: Unified Sources can
      // itself be the actual provider that owns Jett/Sova/Phoenix results.
      // The aggregate bucket may also mirror links from other providers, so
      // exact owner+URL+metadata signatures below remove only those copies.
      final providerSourceKeys = sourceKeysByProvider[providerEntry.key]!;
      for (
        var linkIndex = 0;
        linkIndex < providerEntry.value.length;
        linkIndex++
      ) {
        final link = providerEntry.value[linkIndex];
        final url = link.url?.trim();
        if (url == null || url.isEmpty) continue;
        // Embedded pages have no selectable media rendition. They remain in
        // the server picker, but must not masquerade as an unknown quality.
        if (link.isEmbeddedPlayer) continue;
        if (link.expiresAt != null && !link.expiresAt!.isAfter(checkedAt)) {
          continue;
        }

        final declaredProviderCode = link.providerCode?.trim();
        final providerCode = declaredProviderCode?.isNotEmpty == true
            ? declaredProviderCode!
            : providerEntry.key;
        var sourceProviderCode = providerEntry.key;
        var sourceKey = providerSourceKeys[linkIndex];
        final ownerLinks = linksByProvider[providerCode];
        if (ownerLinks != null) {
          // Aggregate entries retain the original link object. Prefer the
          // owning provider's exact key when it is available; otherwise the
          // Unified Sources bucket remains the activation source.
          final ownerIndex = ownerLinks.indexWhere(
            (candidate) =>
                identical(candidate, link) || _sameRawSource(candidate, link),
          );
          if (ownerIndex >= 0) {
            sourceProviderCode = providerCode;
            sourceKey = sourceKeysByProvider[providerCode]![ownerIndex];
          }
        }
        final headers =
            (link.headers ?? const <String, String>{}).entries.toList()..sort(
              (a, b) => a.key.toLowerCase().compareTo(b.key.toLowerCase()),
            );
        final headerSignature = headers
            .map((entry) => '${entry.key.toLowerCase()}:${entry.value}')
            .join('|');
        final sortedAvailableHeights = link.availableHeights.toSet().toList()
          ..sort();
        final signature = <String>[
          providerCode,
          url,
          link.server?.trim().toLowerCase() ?? '',
          link.quality ?? '',
          link.isM3U8 == true ? 'hls' : '',
          link.isDash == true ? 'dash' : '',
          link.isAdaptive ? 'adaptive' : '',
          link.isEmbeddedPlayer ? 'embedded' : '',
          link.embedRequiresVerification ? 'verification' : '',
          link.sizeToken ?? '',
          headerSignature,
          sortedAvailableHeights.join(','),
        ].join('\u001f');
        if (!seen.add(signature)) continue;

        final availableHeights =
            link.availableHeights.where((height) => height > 0).toSet().toList()
              ..sort((a, b) => b.compareTo(a));
        final parsedHeight = VideoUtils.videoQualityHeight(link.quality ?? '');
        final rawQuality = link.quality?.trim();
        final normalizedQuality = (rawQuality ?? '').trim().toLowerCase();
        final adaptiveLabel =
            normalizedQuality.startsWith('auto') ||
            normalizedQuality.startsWith('adaptive') ||
            normalizedQuality.startsWith('master');
        if (link.isAdaptive || availableHeights.isNotEmpty || adaptiveLabel) {
          // A provider's Auto/master setting is an implementation detail, not
          // a user-selectable quality. Only expose concrete discovered
          // renditions and keep their exact master URL/headers for activation.
          final variantHeights = <int>{...availableHeights};
          if (parsedHeight != null) variantHeights.add(parsedHeight);
          final sortedVariants = variantHeights.toList()
            ..sort((a, b) => b.compareTo(a));
          if (sortedVariants.isEmpty) continue;
          for (final variantHeight in sortedVariants) {
            result.add(
              QualityCatalogEntry(
                providerCode: providerCode,
                sourceProviderCode: sourceProviderCode,
                sourceKey: sourceKey,
                link: link,
                height: variantHeight,
                qualityLabel: '${variantHeight}p',
                adaptiveTargetHeight: variantHeight,
                isAdaptive: true,
              ),
            );
          }
        } else {
          result.add(
            QualityCatalogEntry(
              providerCode: providerCode,
              sourceProviderCode: sourceProviderCode,
              sourceKey: sourceKey,
              link: link,
              height: parsedHeight,
              qualityLabel: _qualityLabel(rawQuality, parsedHeight),
            ),
          );
        }
      }
    }

    // Different servers must remain independently selectable at the same
    // resolution. Only collapse repeated catalogue records that point to the
    // same exact provider source key and rendition.
    final uniqueBySourceAndQuality = <String, QualityCatalogEntry>{};
    for (final entry in result) {
      final key = _qualityIdentity(entry);
      final previous = uniqueBySourceAndQuality[key];
      final entryIsActive = _isActiveSource(
        entry,
        providerCode: activeProviderCode,
        sourceKey: activeSourceKey,
        streamUrl: activeStreamUrl,
      );
      final previousIsActive =
          previous != null &&
          _isActiveSource(
            previous,
            providerCode: activeProviderCode,
            sourceKey: activeSourceKey,
            streamUrl: activeStreamUrl,
          );
      final entryRank = _rankHost(entry.link.server, hostOrder);
      final previousRank = previous == null
          ? 1 << 30
          : _rankHost(previous.link.server, hostOrder);
      if (previous == null ||
          (entryIsActive && !previousIsActive) ||
          (entryIsActive == previousIsActive && entryRank < previousRank)) {
        uniqueBySourceAndQuality[key] = entry;
      }
    }
    final unique = uniqueBySourceAndQuality.values.toList(growable: false);
    unique.sort((left, right) {
      final leftHeight = left.height;
      final rightHeight = right.height;
      if (leftHeight != rightHeight) {
        if (leftHeight == null) return 1;
        if (rightHeight == null) return -1;
        return rightHeight.compareTo(leftHeight);
      }
      final leftRank = _rankHost(left.link.server, hostOrder);
      final rightRank = _rankHost(right.link.server, hostOrder);
      if (leftRank != rightRank) return leftRank.compareTo(rightRank);
      final serverOrder = left.sourceDisplayName.compareTo(
        right.sourceDisplayName,
      );
      if (serverOrder != 0) return serverOrder;
      return left.qualityLabel.compareTo(right.qualityLabel);
    });
    return List<QualityCatalogEntry>.unmodifiable(unique);
  }

  /// User-facing projection: exactly one selectable server per concrete
  /// resolution. The full collect() result remains source-specific for
  /// diagnostics and recovery.
  ///
  /// The active exact source wins. Otherwise measured playback success,
  /// failure ratio and startup latency decide; configured host order is the
  /// deterministic fallback when no useful metrics are available.
  static List<QualityCatalogEntry> bestPerQuality({
    required Iterable<QualityCatalogEntry> entries,
    String? activeProviderCode,
    String? activeSourceKey,
    String? activeStreamUrl,
    List<String>? preferredServerOrder,
  }) {
    final hostOrder =
        preferredServerOrder ?? StreamHostPriorityManager.instance.currentOrder;
    final bestByQuality = <String, QualityCatalogEntry>{};

    for (final entry in entries) {
      final key = _displayQualityIdentity(entry);
      final previous = bestByQuality[key];
      if (previous == null) {
        bestByQuality[key] = entry;
        continue;
      }

      final entryIsActive = _isActiveSource(
        entry,
        providerCode: activeProviderCode,
        sourceKey: activeSourceKey,
        streamUrl: activeStreamUrl,
      );
      final previousIsActive = _isActiveSource(
        previous,
        providerCode: activeProviderCode,
        sourceKey: activeSourceKey,
        streamUrl: activeStreamUrl,
      );
      if (entryIsActive != previousIsActive) {
        if (entryIsActive) bestByQuality[key] = entry;
        continue;
      }

      if (_compareStableServer(entry, previous, hostOrder) < 0) {
        bestByQuality[key] = entry;
      }
    }

    final unique = bestByQuality.values.toList(growable: false);
    unique.sort((left, right) {
      final leftHeight = left.height ?? left.adaptiveTargetHeight;
      final rightHeight = right.height ?? right.adaptiveTargetHeight;
      if (leftHeight != rightHeight) {
        if (leftHeight == null) return 1;
        if (rightHeight == null) return -1;
        return rightHeight.compareTo(leftHeight);
      }
      return left.qualityLabel.compareTo(right.qualityLabel);
    });
    return List<QualityCatalogEntry>.unmodifiable(unique);
  }

  static String _displayQualityIdentity(QualityCatalogEntry entry) {
    final height = entry.height ?? entry.adaptiveTargetHeight;
    if (height != null && height > 0) return 'height:$height';
    final label = entry.qualityLabel
        .trim()
        .toLowerCase()
        .split(' · ')
        .first
        .replaceAll(RegExp(r'\s+'), ' ');
    return 'label:${label.isEmpty ? 'unknown quality' : label}';
  }

  static int _compareStableServer(
    QualityCatalogEntry left,
    QualityCatalogEntry right,
    List<String> hostOrder,
  ) {
    final manager = StreamHostPriorityManager.instance;
    final leftMetrics =
        manager.metricsFor(left.link.server ?? left.sourceDisplayName) ??
        const <String, Object?>{};
    final rightMetrics =
        manager.metricsFor(right.link.server ?? right.sourceDisplayName) ??
        const <String, Object?>{};

    int metric(Map<String, Object?> values, String key) =>
        (values[key] as num?)?.toInt() ?? 0;
    double average(Map<String, Object?> values) =>
        (values['averageStartupMs'] as num?)?.toDouble() ?? 120000;

    final leftSuccesses = metric(leftMetrics, 'successes');
    final rightSuccesses = metric(rightMetrics, 'successes');
    if ((leftSuccesses > 0) != (rightSuccesses > 0)) {
      return leftSuccesses > 0 ? -1 : 1;
    }

    if (leftSuccesses > 0 && rightSuccesses > 0) {
      final leftFailures = metric(leftMetrics, 'failures');
      final rightFailures = metric(rightMetrics, 'failures');
      final leftRatio = leftFailures / (leftSuccesses + leftFailures);
      final rightRatio = rightFailures / (rightSuccesses + rightFailures);
      final reliability = leftRatio.compareTo(rightRatio);
      if (reliability != 0) return reliability;

      final latency = average(leftMetrics).compareTo(average(rightMetrics));
      if (latency != 0) return latency;

      final successCount = rightSuccesses.compareTo(leftSuccesses);
      if (successCount != 0) return successCount;
    } else {
      final leftFailures = metric(leftMetrics, 'failures');
      final rightFailures = metric(rightMetrics, 'failures');
      if ((leftFailures == 0) != (rightFailures == 0)) {
        return leftFailures == 0 ? -1 : 1;
      }
      if (leftFailures != rightFailures) {
        return leftFailures.compareTo(rightFailures);
      }
    }

    final leftRank = _rankHost(left.link.server, hostOrder);
    final rightRank = _rankHost(right.link.server, hostOrder);
    if (leftRank != rightRank) return leftRank.compareTo(rightRank);
    return left.sourceDisplayName.compareTo(right.sourceDisplayName);
  }

  static int _rankHost(String? server, List<String> order) {
    final managerRank = StreamHostPriorityManager.instance.rankOf(server);
    // Explicit test/custom order wins for pinned hosts; measured ranking is
    // used for hosts not included in that list.
    final normalized = (server ?? '').trim().toLowerCase();
    for (var i = 0; i < order.length; i++) {
      final candidate = order[i].trim().toLowerCase();
      if (normalized == candidate ||
          normalized.startsWith('$candidate ') ||
          normalized.startsWith('$candidate-') ||
          normalized.startsWith('${candidate}_') ||
          normalized.startsWith('$candidate/'))
        return i;
    }
    return managerRank;
  }

  static String _qualityIdentity(QualityCatalogEntry entry) {
    final height = entry.height ?? entry.adaptiveTargetHeight;
    final sourceIdentity =
        '${entry.sourceProviderCode.trim().toLowerCase()}::'
        '${entry.sourceKey.trim().toLowerCase()}';
    if (height != null && height > 0) {
      return '$sourceIdentity::height:$height';
    }
    final normalized = entry.qualityLabel
        .trim()
        .toLowerCase()
        .split(' · ')
        .first
        .replaceAll(RegExp(r'\s+'), ' ');
    return '$sourceIdentity::label:'
        '${normalized.isEmpty ? 'unknown quality' : normalized}';
  }

  static bool _isActiveSource(
    QualityCatalogEntry entry, {
    required String? providerCode,
    required String? sourceKey,
    required String? streamUrl,
  }) =>
      providerCode != null &&
      sourceKey != null &&
      streamUrl != null &&
      entry.sourceProviderCode == providerCode &&
      entry.sourceKey == sourceKey &&
      entry.link.url == streamUrl;

  static String _qualityLabel(String? rawQuality, int? parsedHeight) {
    if (parsedHeight != null) return '${parsedHeight}p';
    final value = rawQuality?.trim();
    if (value == null ||
        value.isEmpty ||
        RegExp(
          r'^unknown quality(?:\s+\d+)?$',
          caseSensitive: false,
        ).hasMatch(value)) {
      return 'Unknown quality';
    }
    return value;
  }

  static bool _sameRawSource(RegularVideoLinks left, RegularVideoLinks right) {
    if (left.url != right.url ||
        left.server != right.server ||
        left.quality != right.quality ||
        left.isM3U8 != right.isM3U8 ||
        left.isDash != right.isDash ||
        left.isAdaptive != right.isAdaptive ||
        left.isEmbeddedPlayer != right.isEmbeddedPlayer ||
        left.embedRequiresVerification != right.embedRequiresVerification ||
        left.sizeToken != right.sizeToken ||
        left.expiresAt != right.expiresAt) {
      return false;
    }
    if (!_sameHeaders(left.headers, right.headers)) return false;
    final leftHeights = left.availableHeights.toSet();
    return leftHeights.length == right.availableHeights.toSet().length &&
        leftHeights.containsAll(right.availableHeights);
  }

  static bool _sameHeaders(
    Map<String, String>? left,
    Map<String, String>? right,
  ) {
    final leftHeaders = left ?? const <String, String>{};
    final rightHeaders = right ?? const <String, String>{};
    if (leftHeaders.length != rightHeaders.length) return false;
    for (final entry in leftHeaders.entries) {
      if (rightHeaders[entry.key] != entry.value) return false;
    }
    return true;
  }
}

/// Matches the active playback row to one exact catalog source. A URL/provider
/// pair is not unique: a provider may return several qualities or mirrors that
/// share the same URL. The source key is the same key used by the player's
/// parallel URL/format/header maps, so only the currently playing row is
/// selected and disabled.
abstract final class PlaybackQualitySelection {
  static bool isSelected({
    required QualityCatalogEntry entry,
    required String? activeProviderCode,
    required String? activeSourceKey,
    required String? activeStreamUrl,
    int? adaptiveTrackHeight,
    bool adaptiveAutoSelected = false,
  }) {
    if (entry.sourceProviderCode != activeProviderCode ||
        entry.sourceKey != activeSourceKey ||
        entry.link.url != activeStreamUrl) {
      return false;
    }

    if (!entry.isAdaptive) return true;
    final targetHeight = entry.adaptiveTargetHeight;
    if (targetHeight == null) return adaptiveAutoSelected;
    return adaptiveTrackHeight == targetHeight;
  }
}

/// One concrete rendition used by the app-owned automatic quality policy.
class PlaybackQualityRendition {
  const PlaybackQualityRendition({
    required this.height,
    this.bitrateBitsPerSecond,
  });

  final int height;
  final int? bitrateBitsPerSecond;
}

/// Chooses a concrete quality for the app's one-time automatic startup pass.
/// It does not preserve or expose a provider's Auto setting. A measured
/// connection is treated conservatively so video bitrate stays below a share
/// of the observed transfer rate; without a usable sample, 720p is the default
/// ceiling (or the best lower/lowest rendition the source actually has).
abstract final class PlaybackAutoQualityPolicy {
  static const int defaultFallbackHeight = 720;
  static const double defaultSafetyFactor = 0.72;

  static int? chooseHeight({
    required Iterable<PlaybackQualityRendition> renditions,
    int? measuredBandwidthBitsPerSecond,
    int fallbackHeight = defaultFallbackHeight,
    double safetyFactor = defaultSafetyFactor,
  }) {
    final candidates = renditions
        .where((rendition) => rendition.height > 0)
        .toList(growable: false);
    if (candidates.isEmpty) return null;

    if (measuredBandwidthBitsPerSecond != null &&
        measuredBandwidthBitsPerSecond > 0) {
      final safeBudget =
          measuredBandwidthBitsPerSecond * safetyFactor.clamp(0.1, 0.95);
      final affordable = candidates
          .where((rendition) {
            final required =
                rendition.bitrateBitsPerSecond != null &&
                    rendition.bitrateBitsPerSecond! > 0
                ? rendition.bitrateBitsPerSecond!
                : _estimatedBitrate(rendition.height);
            return required <= safeBudget;
          })
          .toList(growable: false);
      if (affordable.isNotEmpty) {
        return affordable
            .reduce(
              (best, rendition) =>
                  rendition.height > best.height ? rendition : best,
            )
            .height;
      }
      // Even when every advertised rendition exceeds the conservative bitrate
      // budget, prefer the smallest available one rather than falling back to
      // 720p and making an already-slow connection worse.
      return candidates
          .reduce(
            (best, rendition) =>
                rendition.height < best.height ? rendition : best,
          )
          .height;
    }

    final atOrBelowFallback = candidates
        .where((rendition) => rendition.height <= fallbackHeight)
        .toList(growable: false);
    if (atOrBelowFallback.isNotEmpty) {
      return atOrBelowFallback
          .reduce(
            (best, rendition) =>
                rendition.height > best.height ? rendition : best,
          )
          .height;
    }
    return candidates
        .reduce(
          (best, rendition) =>
              rendition.height < best.height ? rendition : best,
        )
        .height;
  }

  static int _estimatedBitrate(int height) {
    if (height >= 2160) return 16_000_000;
    if (height >= 1440) return 9_000_000;
    if (height >= 1080) return 5_500_000;
    if (height >= 900) return 4_000_000;
    if (height >= 720) return 3_000_000;
    if (height >= 540) return 1_900_000;
    if (height >= 480) return 1_500_000;
    if (height >= 360) return 900_000;
    if (height >= 240) return 550_000;
    return 350_000;
  }
}
